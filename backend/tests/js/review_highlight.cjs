const fs = require('fs');
const path = require('path');

const html = fs.readFileSync(path.join(__dirname, '../../src/youju/admin/review.html'), 'utf8');
const js = html.split('<script>')[1].split('</script>')[0];
new Function(js); // 整段脚本语法检查
const DATE_RE = eval(js.match(/const DATE_RE = (\/.*\/g);/)[1]);
const RANGE_END_RE = eval(js.match(/const RANGE_END_RE = (\/.*\/);/)[1]);
const src = js.slice(js.indexOf('  function evidenceNode'), js.indexOf('  function setCount'));
const el = (tag, cls, text) => ({ tag, className: cls || '', textContent: text, parts: [], append(...parts) { this.parts.push(...parts); } });
const evidenceNode = new Function('DATE_RE', 'RANGE_END_RE', 'el', `${src}; return evidenceNode;`)(DATE_RE, RANGE_END_RE, el);

// 所有标出的位置，按出现顺序用"|"连接；同时检查拼回去的文字与原文一致
function show(text, date) {
  const box = evidenceNode(text, date);
  const body = box.parts.filter((p) => !(p && p.className === 'miss'));
  const joined = body.length ? body.map((p) => (typeof p === 'string' ? p : p.textContent)).join('') : box.textContent;
  if (joined !== text) return `拼接出错：${joined}`;
  const marks = body.filter((p) => p && p.tag === 'mark');
  const miss = box.parts.some((p) => p && p.className === 'miss');
  if (!marks.length) return miss ? '不高亮' : '不高亮但没有提示';
  return marks.map((mark) => `${mark.className === 'unsure' ? '虚' : '实'}:${mark.textContent}`).join('|');
}

