"""按标题给文件打的筛选标签（D-051 第三阶段）：支持方式、产业方向。

- 只看标题关键词，**只用于筛选**：小程序筛选弹层写明"按标题归类，仅供检索参考，非官方分类"，
  列表和详情都不返回、不展示这些标签。详情页的"支持方式"只显示人工核对通过的（youju.fields），
  与这里互不影响；两边用同一套词（资金支持、贷款贴息、资格认定、入库备案、项目立项），筛选另有
  "征集入选"。不涉及金额。
- 一份文件可以有多个标签，也可以没有。每个标签有自己的关键词；标题含排除词的不打这个标签
  （TagRules.exclude 对所有标签，各标签的第三项只对这一个标签）。
- 支持方式只对申报通知和名单（与项目类别相同，SUPPORT_KINDS）；产业方向对所有类型。
- 与项目类别一样，入库时算好存在 rule_supports / rule_industries（按标签顺序用逗号连起来，没有标签
  存空串），筛选只比较这两列；规则改了由 youju reclassify 重算；还没算的（NULL，刚升级）筛选时
  当场按同一套规则判断，结果一样。
- 产业方向的标签名不用"人工智能""智能""AI""大模型"等字样（小程序界面不出现这些字），标题里有
  人工智能、大模型的归"数字经济"，有智能制造、智能工厂的归"先进制造"。
- 关键词避开发文机关名称：标题常以"××省工业和信息化厅""××局"开头，所以不用"信息化""能源"
  "经济""工业"这类会命中机关名称的单字词，改用"数字化""新能源"等。
"""

from __future__ import annotations

from dataclasses import dataclass

from sqlalchemy import ColumnElement, and_, false, func, not_, or_

from youju.categories import CATEGORY_KINDS

# （标签, 关键词, 只对这个标签的排除词）
Rule = tuple[str, tuple[str, ...], tuple[str, ...]]


@dataclass(frozen=True)
class TagRules:
    rules: tuple[Rule, ...]
    # 标题含这些词的，什么标签都不打
    exclude: tuple[str, ...] = ()

    @property
    def labels(self) -> tuple[str, ...]:
        return tuple(name for name, _, _ in self.rules)

    def tags(self, title: str) -> tuple[str, ...]:
        """按标题算出的标签（按标签顺序），没有时为空。"""
        if any(w in title for w in self.exclude):
            return ()
        return tuple(
            name
            for name, words, skip in self.rules
            if any(w in title for w in words) and not any(w in title for w in skip)
        )

    def stored(self, title: str) -> str:
        """存进数据库的值：标签用逗号连起来，没有标签是空串（和"还没算"的 NULL 区分开）。"""
        return ",".join(self.tags(title))

    def sql_filter(self, title: ColumnElement[str], labels: list[str]) -> ColumnElement[bool]:
        """与 tags 完全相同的判断写成 SQL：标题有选中的任一标签。"""
        parts = []
        for name, words, skip in self.rules:
            if name not in labels:
                continue
            parts.append(and_(_any(title, words), *(not_(_any(title, (w,))) for w in skip)))
        if not parts:
            return false()
        return and_(*(not_(_any(title, (w,))) for w in self.exclude), or_(*parts))

    def filter(
        self,
        column: ColumnElement[str | None],
        title: ColumnElement[str],
        labels: list[str],
        *,
        complete: bool = False,
    ) -> ColumnElement[bool]:
        """筛选（同一组里多选取并集）：算好的比较存的那一列，还没算的当场按标题规则判断。
        complete 为真表示调用方已确认这一列没有"还没算的"（NULL），不带当场判断那一段
        （它写成 SQL 很长）。"""
        wrapped = func.concat(",", column, ",")
        stored = or_(*(wrapped.contains(f",{name},", autoescape=True) for name in labels))
        if complete:
            return and_(column.is_not(None), stored)
        return or_(
            and_(column.is_not(None), stored),
            and_(column.is_(None), self.sql_filter(title, labels)),
        )


def _any(title: ColumnElement[str], words: tuple[str, ...]) -> ColumnElement[bool]:
    return or_(*(title.contains(w, autoescape=True) for w in words))


